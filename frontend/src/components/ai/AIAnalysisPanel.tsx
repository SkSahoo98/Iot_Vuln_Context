import type { Explanation, Finding, RiskItem } from "../../api/types";
import { formatGeneratedAt } from "../../lib/format";
import { FindingEvidence } from "../FindingEvidence";
import { RemediationList } from "../RemediationList";
import { LoadingState } from "../common/LoadingState";
import { SeverityBadge } from "../common/SeverityBadge";
import { AIStatus } from "./AIStatus";

type Props = {
  finding: Finding;
  riskItem: RiskItem | null;
  explanation: Explanation | null;
  loading: boolean;
  error: string | null;
  onRegenerate: () => void;
};

function Section({
  title,
  children,
  note,
}: {
  title: string;
  children: React.ReactNode;
  note?: string;
}) {
  return (
    <section className="glass-inset rounded-2xl p-4">
      <div className="mb-2.5 flex flex-wrap items-center justify-between gap-2">
        <h3 className="text-[11px] font-medium tracking-[0.12em] text-[var(--muted)] uppercase">
          {title}
        </h3>
        {note ? (
          <span className="text-[11px] text-[var(--muted)]">{note}</span>
        ) : null}
      </div>
      <div className="text-sm leading-relaxed text-[var(--muted)]">{children}</div>
    </section>
  );
}

export function AIAnalysisPanel({
  finding,
  riskItem,
  explanation,
  loading,
  error,
  onRegenerate,
}: Props) {
  const generatedAt = formatGeneratedAt(explanation?.generated_at);

  return (
    <div className="space-y-4">
      <div className="flex flex-wrap items-start justify-between gap-3">
        <AIStatus explanation={explanation} loading={loading} />
        <button
          type="button"
          onClick={onRegenerate}
          disabled={loading}
          className="btn-soft rounded-full border border-[var(--accent)]/40 bg-[var(--accent-soft)] px-3.5 py-2 text-xs font-medium text-[var(--accent)] hover:bg-[var(--accent)]/20 disabled:opacity-50"
        >
          Regenerate AI Analysis
        </button>
      </div>

      <div className="glass-inset relative overflow-hidden rounded-2xl p-4">
        <div
          className="pointer-events-none absolute -right-10 -top-12 h-32 w-32 rounded-full bg-[var(--accent)]/12 blur-3xl"
          aria-hidden
        />
        <p className="relative text-[11px] tracking-[0.12em] text-[var(--muted)] uppercase">
          What was found?
        </p>
        <h2 className="font-display relative mt-1 text-lg font-semibold">
          {finding.title}
        </h2>
        <p className="relative mt-2 text-sm text-[var(--muted)]">
          {finding.description}
        </p>
        <div className="relative mt-3 flex flex-wrap gap-2 text-sm">
          <SeverityBadge severity={finding.severity} />
          {riskItem ? (
            <span className="premium-badge rounded-full border border-white/10 bg-white/[0.04] px-2.5 py-0.5 text-[11px]">
              Authoritative risk:{" "}
              <span className="mono font-semibold">
                {riskItem.score} {riskItem.risk_level}
              </span>
            </span>
          ) : null}
        </div>
      </div>

      {loading ? (
        <LoadingState message="Qwen3 is analyzing verified evidence..." />
      ) : null}

      {error ? (
        <p className="rounded-2xl border border-[var(--danger)]/30 bg-[var(--danger)]/[0.08] px-4 py-3 text-sm text-[var(--danger)]">
          {error}
        </p>
      ) : null}

      {!loading && explanation?.source === "fallback" ? (
        <p className="rounded-2xl border border-[var(--warn)]/30 bg-[var(--warn)]/[0.08] px-4 py-3 text-sm text-[var(--warn)]">
          AI model unavailable — displaying evidence-grounded fallback
          explanation.
        </p>
      ) : null}

      {!loading && explanation ? (
        <>
          {explanation.source === "ollama" ? (
            <p className="text-xs text-[var(--muted)]">
              Generated by {explanation.model ?? "qwen3:8b"} via local Ollama
              {generatedAt ? ` · ${generatedAt}` : ""}
            </p>
          ) : (
            <p className="text-xs text-[var(--muted)]">
              Deterministic rule-based explanation
              {generatedAt ? ` · ${generatedAt}` : ""}
            </p>
          )}

          <div className="grid gap-3 lg:grid-cols-2">
            <Section title="Why does it matter?">{explanation.why_it_matters}</Section>
            <Section title="What could happen?">{explanation.potential_impact}</Section>
            <Section
              title="Potential attack scenario"
              note="Potential scenario — not an observed attack"
            >
              {explanation.attack_scenario}
            </Section>
            <Section title="What should be done?">
              <RemediationList items={explanation.remediation} />
            </Section>
            <Section title="IoT context">{explanation.iot_context}</Section>
            <Section title="AI risk interpretation">
              {riskItem ? (
                <p className="mb-2 text-xs">
                  Authoritative risk remains{" "}
                  <span className="mono text-[var(--text)]">
                    {riskItem.score} {riskItem.risk_level}
                  </span>
                  . AI interprets this score; it does not recalculate it.
                </p>
              ) : null}
              {explanation.risk_explanation}
            </Section>
          </div>

          <Section title="Summary">{explanation.summary}</Section>

          <section className="glass-inset rounded-2xl border-dashed p-4">
            <h3 className="mb-2.5 text-[11px] font-medium tracking-[0.12em] text-[var(--muted)] uppercase">
              Technical evidence
            </h3>
            <FindingEvidence evidence={finding.evidence} />
          </section>
        </>
      ) : null}
    </div>
  );
}

