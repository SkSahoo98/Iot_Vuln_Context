r"""One-command database setup for development.

Creates .env (if needed), database, migration, seed data, and runs tests.

Usage (interactive — recommended):
    cd backend
    .\\.venv\\Scripts\\Activate.ps1
    python scripts/setup_database.py

Usage (non-interactive — password via environment variable):
    $env:IOT_POSTGRES_PASSWORD = "your_password"
    python scripts/setup_database.py
"""

from __future__ import annotations

import argparse
import os
import subprocess
import sys
from pathlib import Path

BACKEND_ROOT = Path(__file__).resolve().parents[1]
PROJECT_ROOT = BACKEND_ROOT.parent
ENV_CANDIDATES = [PROJECT_ROOT / ".env", BACKEND_ROOT / ".env"]


def write_env(password: str) -> Path:
    env_path = PROJECT_ROOT / ".env"
    content = f"""# Auto-generated by setup_database.py — do not commit.
ENVIRONMENT=development
PROJECT_NAME=IoT Security Framework

DATABASE_URL=postgresql+psycopg://postgres:{password}@localhost:5432/iot_security
POSTGRES_ADMIN_URL=postgresql+psycopg://postgres:{password}@localhost:5432/postgres

API_HOST=127.0.0.1
API_PORT=8000
"""
    env_path.write_text(content, encoding="utf-8")
    print(f"Wrote {env_path}")
    return env_path


def env_is_configured() -> bool:
    for path in ENV_CANDIDATES:
        if not path.exists():
            continue
        text = path.read_text(encoding="utf-8")
        if "CHANGE_ME" not in text:
            return True
    return False


def resolve_password(cli_password: str | None) -> str | None:
    if cli_password:
        return cli_password
    env_password = os.environ.get("IOT_POSTGRES_PASSWORD")
    if env_password:
        return env_password
    if env_is_configured():
        return None
    try:
        import getpass

        return getpass.getpass("PostgreSQL password for user 'postgres': ")
    except (EOFError, KeyboardInterrupt):
        return None


def run_step(label: str, command: list[str]) -> None:
    print(f"\n=== {label} ===")
    result = subprocess.run(command, cwd=BACKEND_ROOT, check=False)
    if result.returncode != 0:
        raise SystemExit(f"Step failed: {label} (exit code {result.returncode})")
    print(f"OK: {label}")


def main() -> None:
    parser = argparse.ArgumentParser(description="Set up IoT Security Framework database")
    parser.add_argument(
        "--password",
        help="PostgreSQL postgres user password (prefer IOT_POSTGRES_PASSWORD env var)",
    )
    parser.add_argument(
        "--skip-tests",
        action="store_true",
        help="Skip pytest after seeding",
    )
    args = parser.parse_args()

    if str(BACKEND_ROOT) not in sys.path:
        sys.path.insert(0, str(BACKEND_ROOT))

    password = resolve_password(args.password)
    if password is not None:
        if not password.strip():
            raise SystemExit("Password cannot be empty.")
        write_env(password)
    elif not env_is_configured():
        print(
            "No .env found and no password provided.\n"
            "Either:\n"
            "  1. Run this script interactively in your terminal, or\n"
            "  2. Set IOT_POSTGRES_PASSWORD, or\n"
            "  3. Create .env manually from .env.example"
        )
        raise SystemExit(1)

    # Clear settings cache so new .env is picked up.
    from app.core.config import get_settings

    get_settings.cache_clear()

    python = sys.executable
    run_step("Create database", [python, "scripts/create_database.py"])
    run_step("Apply migrations", [python, "-m", "alembic", "upgrade", "head"])
    run_step("Seed data", [python, "scripts/seed_data.py"])

    if not args.skip_tests:
        run_step("Run tests", [python, "-m", "pytest", "-v"])

    print("\nDatabase setup complete.")
    print("Verify ESP32-02:")
    print(
        '  psql -U postgres -d iot_security -c '
        '"SELECT d.device_name, rs.score, rs.risk_level '
        'FROM risk_scores rs JOIN devices d ON d.id = rs.device_id '
        "WHERE d.device_name = 'ESP32-02';\""
    )


if __name__ == "__main__":
    main()
